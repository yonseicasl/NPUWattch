#!/usr/bin/env python3
"""
gen_decoder_rtl.py -- SRAM row-decoder RTL generator (FPGA-BRAM style).

Extends the surviving legacy generator (~/ys_knu/sram/gen_decoder.py): the
address is registered at posedge clk when en is high, decoded one-hot, and
the wordline outputs are gated combinationally by wlen so the WL pulse width
is set by the wlen window (the array TB drives WL high at T+2..T+5 of each
10 ns op -- the decoder TB drives wlen with the same window).

Module name is dec_<R>x<C>: the RTL is identical for a given row count, but
the synthesized netlist differs per column count (the WL output load used
for driver sizing scales with cols), so configs get distinct cell names --
consistent with the array_X<S>_<R>x<C> store naming.

Usage: gen_decoder_rtl.py --rows R --cols C -o dec_RxC.v
"""
import argparse


def log2i(n):
    b = (n - 1).bit_length()
    if n < 2 or (1 << b) != n:
        raise SystemExit("gen_decoder_rtl: rows must be a power of two >= 2 "
                         "(got %d)" % n)
    return b


def generate(rows, cols):
    abits = log2i(rows)
    top = "dec_%dx%d" % (rows, cols)
    return top, """\
// %s -- %d-row SRAM wordline decoder (posedge-latched, BRAM style)
// Generated by gen_decoder_rtl.py -- do not edit directly.
//   clk  : address register clock (one op per 10 ns in the SRAM flow)
//   en   : address register enable (address held when low)
//   wlen : wordline pulse window; wl is one-hot(addr_q) AND wlen
//   cols=%d only affects the WL output load used at synthesis time.
module %s (
    input  wire            clk,
    input  wire            en,
    input  wire            wlen,
    input  wire [%d:0]     addr,
    output wire [%d:0]     wl
);
    reg [%d:0] addr_q;
    always @(posedge clk)
        if (en) addr_q <= addr;

    localparam [%d:0] ONE = {{%d{1'b0}}, 1'b1};
    assign wl = (ONE << addr_q) & {%d{wlen}};
endmodule
""" % (top, rows, cols, top, abits - 1, rows - 1, abits - 1,
       rows - 1, rows - 1, rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, required=True)
    ap.add_argument("--cols", type=int, required=True)
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    top, rtl = generate(a.rows, a.cols)
    with open(a.out, "w") as f:
        f.write(rtl)
    print("gen_decoder_rtl: %s (top=%s, %d rows -> %d addr bits)"
          % (a.out, top, a.rows, log2i(a.rows)))


if __name__ == "__main__":
    main()
